    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblMuonTra.getSelectedRow(); // Lấy dòng được chọn
            if (selectedRow != -1) {
                String maPhieu = tblMuonTra.getValueAt(selectedRow, 0).toString(); // Lấy Mã Phiếu
                String tinhTrang = tblMuonTra.getValueAt(selectedRow, 2).toString(); // Lấy Tình Trạng

                // Kiểm tra tình trạng phiếu
                if ("Đang mượn".equalsIgnoreCase(tinhTrang)) {
                    JOptionPane.showMessageDialog(this, "Không thể xóa phiếu khi tình trạng đang mượn.");
                    return;
                }

                // Xác nhận xóa
                int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn xóa không?", "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
                if (confirm != JOptionPane.YES_OPTION) {
                    return; // Nếu người dùng chọn không, thoát khỏi phương thức
                }

                // Bắt đầu xóa từ CTPHIEUMUONTRA
                String deleteCTQuery = "DELETE FROM CTPHIEUMUONTRA WHERE MaPhieu = ?";
                try (Connection connection = MyConnection.getConnection();
                     PreparedStatement psCT = connection.prepareStatement(deleteCTQuery)) {
                    psCT.setString(1, maPhieu);
                    psCT.executeUpdate();
                } catch (SQLException e) {
                    e.printStackTrace();
                    JOptionPane.showMessageDialog(this, "Lỗi khi xóa chi tiết phiếu: " + e.getMessage());
                    return;
                }

                // Xóa phiếu khỏi PHIEUMUONTRA
                String deletePhieuQuery = "DELETE FROM PHIEUMUONTRA WHERE MaPhieu = ?";
                try (Connection connection = MyConnection.getConnection();
                     PreparedStatement psPhieu = connection.prepareStatement(deletePhieuQuery)) {
                    psPhieu.setString(1, maPhieu);
                    psPhieu.executeUpdate();
                    JOptionPane.showMessageDialog(this, "Xóa phiếu thành công!");
                } catch (SQLException e) {
                    e.printStackTrace();
                    JOptionPane.showMessageDialog(this, "Lỗi khi xóa phiếu: " + e.getMessage());
                }

                // Tải lại dữ liệu vào bảng
                loadData();
            } else {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn một dòng để xóa.");
            }
    }//GEN-LAST:event_btnXoaActionPerformed

