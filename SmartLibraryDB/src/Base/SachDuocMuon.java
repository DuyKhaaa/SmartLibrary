    private void btnExportPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportPDFActionPerformed
        // TODO add your handling code here:
        PrinterJob printerJob = PrinterJob.getPrinterJob();
        printerJob.setPrintable(new Printable() {
            @Override
            public int print(Graphics g, PageFormat pageFormat, int pageIndex) throws PrinterException {
                if (pageIndex > 0) {
                    return NO_SUCH_PAGE;
                }

                Graphics2D g2d = (Graphics2D) g;
                g2d.translate(pageFormat.getImageableX(), pageFormat.getImageableY());

                // Vẽ tiêu đề
                String title = "Thống kê sách được mượn";
                g2d.setFont(new Font("Arial", Font.BOLD, 20));
                FontMetrics fm = g2d.getFontMetrics();
                int titleWidth = fm.stringWidth(title);
                g2d.drawString(title, (int) ((pageFormat.getWidth() - titleWidth) / 2), 50);

                // Vẽ ngày giờ hiện tại
                String currentDateTimeString = new SimpleDateFormat("dd-MM-yyyy HH:mm:ss").format(new Date());
                g2d.setFont(new Font("Arial", Font.PLAIN, 12));
                g2d.drawString(currentDateTimeString, 10, 70);

                // Vẽ bảng
                int y = 100;
                g2d.setFont(new Font("Arial", Font.BOLD, 14));
                g2d.drawString("Mã sách", 50, y);
                g2d.drawString("Tên sách", 200, y);
                g2d.drawString("Số lượng mượn", 450, y);
                y += 20;

                g2d.setFont(new Font("Arial", Font.PLAIN, 12));
                for (int i = 0; i < tblThongKeSachDuocMuon.getRowCount(); i++) {
                    g2d.drawString((String) tblThongKeSachDuocMuon.getValueAt(i, 0), 50, y);
                    g2d.drawString((String) tblThongKeSachDuocMuon.getValueAt(i, 1), 200, y);
                    g2d.drawString(String.valueOf(tblThongKeSachDuocMuon.getValueAt(i, 2)), 450, y);
                    y += 20;
                }

                // Vẽ biểu đồ
                int chartY = y + 20; // Vị trí vẽ biểu đồ
                PanelBieuDo.printAll(g2d.create(0, chartY, (int) pageFormat.getWidth(), (int) pageFormat.getHeight() - chartY));

                return PAGE_EXISTS;
            }
        });

        boolean doPrint = printerJob.printDialog();
        if (doPrint) {
            try {
                printerJob.print();
            } catch (PrinterException e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Lỗi khi in: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnExportPDFActionPerformed

