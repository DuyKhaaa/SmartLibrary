    private void createPDF(String maDG, String hoTen) {
        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Chọn vị trí lưu file PDF");
        fileChooser.setSelectedFile(new File("Card_" + maDG + ".pdf"));

        int userSelection = fileChooser.showSaveDialog(this);
        if (userSelection == JFileChooser.APPROVE_OPTION) {
            File fileToSave = fileChooser.getSelectedFile();
            try {
                Document document = new Document();
                PdfWriter writer = PdfWriter.getInstance(document, new FileOutputStream(fileToSave));
                document.open();

                // Thêm font hỗ trợ tiếng Việt
                BaseFont bf = BaseFont.createFont("c:/windows/fonts/times.ttf", BaseFont.IDENTITY_H, BaseFont.EMBEDDED);
                Font titleFont = new Font(bf, 30, Font.BOLD);
                Font contentFont = new Font(bf, 12, Font.NORMAL);

                // Vẽ tiêu đề
                String title = "THÔNG TIN ĐỘC GIẢ";
                Paragraph titleParagraph = new Paragraph(title, titleFont);
                titleParagraph.setAlignment(Element.ALIGN_CENTER);
                document.add(titleParagraph);
                document.add(new Paragraph("\n")); // Dòng trống

                // Thêm thông tin độc giả
                document.add(new Paragraph("Mã độc giả: " + maDG, contentFont));
                document.add(new Paragraph("Họ tên: " + hoTen, contentFont));

                // Lấy thông tin từ cơ sở dữ liệu
                String query = "SELECT * FROM DOCGIA WHERE MaDG = ?";
                try (Connection conn = MyConnection.getConnection(); 
                     PreparedStatement pstmt = conn.prepareStatement(query)) {
                    pstmt.setString(1, maDG);
                    ResultSet rs = pstmt.executeQuery();

                    if (rs.next()) {
                        String maLoai = rs.getString("MaLoai");
                        String ngaySinh = rs.getString("NgaySinh");
                        String sdt = rs.getString("SDT");
                        String ngayLapThe = rs.getString("NgayLapThe");
                        String ngayHetHan = rs.getString("NgayHetHan");

                        // Thêm các thông tin vào PDF
                        document.add(new Paragraph("Loại độc giả: " + maLoai, contentFont));
                        document.add(new Paragraph("Ngày sinh: " + ngaySinh, contentFont));
                        document.add(new Paragraph("Số điện thoại: " + sdt, contentFont));
                        document.add(new Paragraph("Ngày lập thẻ: " + ngayLapThe, contentFont));
                        document.add(new Paragraph("Ngày hết hạn: " + ngayHetHan, contentFont));
                    }
                } catch (SQLException e) {
                    e.printStackTrace();
                }

                // Tạo mã QR
                QRCodeWriter qrCodeWriter = new QRCodeWriter();
                BitMatrix qrBitMatrix = qrCodeWriter.encode(maDG, BarcodeFormat.QR_CODE, 100, 100);
                BufferedImage qrImage = MatrixToImageWriter.toBufferedImage(qrBitMatrix);
                ByteArrayOutputStream qrBaos = new ByteArrayOutputStream();
                ImageIO.write(qrImage, "png", qrBaos);
                com.itextpdf.text.Image qrPdfImage = com.itextpdf.text.Image.getInstance(qrBaos.toByteArray());

                // Tạo mã vạch
                Barcode128 barcode128 = new Barcode128();
                barcode128.setCode(maDG);
                com.itextpdf.text.Image barcodeImage = barcode128.createImageWithBarcode(writer.getDirectContent(), null, null);

                // Thêm mã QR và mã vạch vào PDF
                // Tạo bảng và thiết lập thuộc tính
                PdfPTable table = new PdfPTable(2);
                table.setWidthPercentage(100);
                // Tạo mã QR
                PdfPCell qrCell = new PdfPCell(qrPdfImage);
                qrCell.setHorizontalAlignment(Element.ALIGN_CENTER); // Căn giữa
                qrCell.setVerticalAlignment(Element.ALIGN_MIDDLE); // Căn giữa theo chiều dọc
                qrCell.setBorder(PdfPCell.NO_BORDER); // Loại bỏ viền cho mã QR
                // Thêm mã QR vào bảng
                table.addCell(qrCell);

                // Tạo ô cho mã vạch
                PdfPCell barcodeCell = new PdfPCell(barcodeImage);
                barcodeCell.setHorizontalAlignment(Element.ALIGN_CENTER); // Căn giữa
                barcodeCell.setVerticalAlignment(Element.ALIGN_MIDDLE); // Căn giữa theo chiều dọc
                barcodeCell.setBorder(PdfPCell.NO_BORDER); // Loại bỏ viền
                // Thêm ô mã vạch vào bảng
                table.addCell(barcodeCell);
                // Thêm một dòng trống trước khi thêm bảng
                document.add(new Paragraph("\n"));
                document.add(table);

                document.close();
                JOptionPane.showMessageDialog(this, "Đã tạo PDF: " + fileToSave.getAbsolutePath());
            } catch (Exception e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Lỗi khi tạo PDF: " + e.getMessage());
            }
        }
    }
