    private void loadData() {
        DefaultTableModel model = (DefaultTableModel) tblThongKeSachDuocMuon.getModel();
        model.setRowCount(0);  // Xóa dữ liệu cũ

        try (Connection conn = MyConnection.getConnection();
             CallableStatement stmt = conn.prepareCall("{call sp_ThongKeSachDuocMuon}")) {
             
            ResultSet rs = stmt.executeQuery();
            while (rs.next()) {
                String maSach = rs.getString("MaSach");
                String tenSach = rs.getString("TenSach");
                int soLuongMuon = rs.getInt("SoLuongMuon");
                model.addRow(new Object[]{maSach, tenSach, soLuongMuon});
            }
            // Vẽ biểu đồ sau khi tải dữ liệu
            drawChart(model);
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi khi tải dữ liệu: " + e.getMessage());
        }
    }
    private void drawChart(DefaultTableModel model) {
        DefaultCategoryDataset dataset = new DefaultCategoryDataset();

        for (int i = 0; i < model.getRowCount(); i++) {
            String tenSach = (String) model.getValueAt(i, 1);
            int soLuongMuon = (int) model.getValueAt(i, 2);
            dataset.addValue(soLuongMuon, "Số lượng mượn", tenSach);
        }

        JFreeChart chart = ChartFactory.createBarChart(
                "Thống kê sách được mượn", // Tiêu đề biểu đồ
                "Tên sách", // Trục X
                "Số lượng", // Trục Y
                dataset // Dữ liệu
        );

        ChartPanel chartPanel = new ChartPanel(chart);
        chartPanel.setPreferredSize(PanelBieuDo.getSize());
        PanelBieuDo.removeAll();
        PanelBieuDo.add(chartPanel);
        PanelBieuDo.revalidate();
        PanelBieuDo.repaint();
    }
