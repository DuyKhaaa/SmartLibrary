    private void loadDataToTable() {
        //String query = "select * from DOCGIA";
        String query = "select DOCGIA.MaDG, DOCGIA.HoTen, LOAIDOCGIA.TenLoai, DOCGIA.NgaySinh, DOCGIA.SDT, DOCGIA.NgayLapThe " +
                       "from DOCGIA " + "join LOAIDOCGIA on DOCGIA.MaLoai = LOAIDOCGIA.MaLoai";        
        ResultSet rs = MyConnection.executeQuery(query);
        
        if (rs == null) {
            // Xử lý khi không lấy được dữ liệu
            return;
        }
        
        try {
            tableModel = (DefaultTableModel) tblDSDocGia.getModel();
            tableModel.setRowCount(0); // Xóa các hàng cũ

            while (rs.next()) {
                String MaDG = rs.getString("MaDG");
                String HoTen = rs.getString("HoTen");
                //String MaLoai = rs.getString("MaLoai");
                String TenLoai = rs.getString("TenLoai");
                String NgaySinh = rs.getString("NgaySinh");
                String SDT = rs.getString("SDT");
                String NgayLapThe = rs.getString("NgayLapThe");
                
                // Thêm dòng mới vào JTable
                tableModel.addRow(new Object[]{MaDG, HoTen, TenLoai, NgaySinh, SDT, NgayLapThe});
            }
        } catch (SQLException e) {
            e.printStackTrace();
        } finally {
            try {
                rs.close();
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }
