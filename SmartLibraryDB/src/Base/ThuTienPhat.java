    private void loadDataToTable() {
        String query = "select * from PHIEUTHUTIENPHAT";
        ResultSet rs = MyConnection.executeQuery(query);
        
        if (rs == null) {
            // Xử lý khi không lấy được dữ liệu
            return;
        }
        
        try {
            tableModel = (DefaultTableModel) tblThuTienPhat.getModel();
            tableModel.setRowCount(0); // Xóa các hàng cũ

            while (rs.next()) {
                String MaPhieuThu = rs.getString("MaPhieuThu");
                String MaPhieu = rs.getString("MaPhieu");
                String NgayLap = rs.getString("NgayLap");
                String LyDo = rs.getString("LyDo");
                int SoTien = rs.getInt("SoTien");

                // Thêm dòng mới vào tableModel
                tableModel.addRow(new Object[]{MaPhieuThu, MaPhieu, NgayLap, LyDo, SoTien});
            }
        } catch (SQLException e) {
            e.printStackTrace();
        } finally {
            try {
                rs.close();
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }
