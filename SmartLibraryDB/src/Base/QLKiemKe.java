    private void loadData() {
        DefaultTableModel model = (DefaultTableModel) tblKiemKe.getModel();
        model.setRowCount(0); // Xóa dữ liệu hiện có

        try {
            // Thiết lập kết nối
            Connection conn = MyConnection.getConnection();
            Statement stmt = conn.createStatement();
            String sql = "SELECT p.MaPhieuKK, p.NgayLap, n.HoTen " +
                         "FROM PHIEUKIEMKE p " +
                         "JOIN NhanVien n ON p.MaNV = n.MaNV"; // Cập nhật tên bảng và trường theo nhu cầu
            
            ResultSet rs = stmt.executeQuery(sql);
            while (rs.next()) {
                String maPhieuKK = rs.getString("MaPhieuKK");
                String ngayLap = rs.getString("NgayLap");
                String tenNV = rs.getString("HoTen");

                model.addRow(new Object[]{maPhieuKK, ngayLap, tenNV});
            }
            rs.close();
            stmt.close();
            conn.close();
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
