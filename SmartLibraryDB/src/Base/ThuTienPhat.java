    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblThuTienPhat.getSelectedRow();
        if (selectedRow != -1) { // Kiểm tra nếu có dòng nào được chọn
            // Lấy thông tin từ bảng
            String MaPhieuThu = tblThuTienPhat.getValueAt(selectedRow, 0).toString();
            String MaPhieu = tblThuTienPhat.getValueAt(selectedRow, 1).toString();
            String NgayLap = tblThuTienPhat.getValueAt(selectedRow, 2).toString();
            String LyDo = tblThuTienPhat.getValueAt(selectedRow, 3).toString();
            String SoTien = tblThuTienPhat.getValueAt(selectedRow, 4).toString();
          // Chuyển hướng sang LapPhieuThu để sửa thông tin
            LapPhieuThu lpthu = new LapPhieuThu();
            lpthu.setMaPhieuThu(MaPhieuThu);
            lpthu.setMaPhieu(MaPhieu);
            lpthu.setNgayLap(NgayLap);
            lpthu.setLyDo(LyDo);
            lpthu.setSoTien(SoTien);
            lpthu.setUpdateMode(true); // Chế độ chỉnh sửa
            lpthu.setVisible(true);
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn phiếu thu cần sửa.");
        }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
          int selectedRow = tblThuTienPhat.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn phiếu thu cần xóa.");
            return;
        }

        String MaPhieuThu = tableModel.getValueAt(selectedRow, 0).toString();

        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn xóa phiếu thu này không?", "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            String sql = "delete from PHIEUTHUTIENPHAT where MaPhieuThu = ?";
            try (Connection con = MyConnection.getConnection();
                 PreparedStatement ps = con.prepareStatement(sql)) {
                ps.setString(1, MaPhieuThu);
                int rowsAffected = ps.executeUpdate();
                if (rowsAffected > 0) {
                    JOptionPane.showMessageDialog(this, "Xóa phiếu thu thành công.");
                    tableModel.removeRow(selectedRow);
                } else {
                    JOptionPane.showMessageDialog(this, "Xóa phiếu thu thất bại.");
                }
            } catch (SQLException e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Xóa phiếu thu thất bại: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed
    
