    private void loadDataToTable() {
        String query = "select * from NHANVIEN";
        ResultSet rs = MyConnection.executeQuery(query);

        if (rs == null) {
            // Xử lý khi không lấy được dữ liệu
            return;
        }

        try {
            tableModel = (DefaultTableModel) tblDSNhanVien.getModel();
            tableModel.setRowCount(0); // Xóa các hàng cũ

            while (rs.next()) {
                String MaNV = rs.getString("MaNV");
                String HoTen = rs.getString("HoTen");
                String NgaySinh = rs.getString("NgaySinh");
                String DiaChi = rs.getString("DiaChi");
                String SDT = rs.getString("SDT");
                String Email = rs.getString("Email");
                String NgayVaoLam = rs.getString("NgayVaoLam");
                String MaBP = rs.getString("MaBP");
                String MatKhau = rs.getString("MatKhau");

                // Thêm dòng mới vào JTable
                tableModel.addRow(new Object[]{MaNV, HoTen, NgaySinh, DiaChi, SDT, Email, NgayVaoLam, MaBP, MatKhau});
            }
        } catch (SQLException e) {
            e.printStackTrace();
        } finally {
            try {
                rs.close();
            } catch (SQLException e) {
                e.printStackTrace();
            }
        }
    }

