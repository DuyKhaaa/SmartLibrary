    private void btnLuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLuuActionPerformed
        // TODO add your handling code here:
        String maSach = txtMaSach.getText();
        String tenSach = txtTenSach.getText();
        String triGia = txtTriGia.getText();
        String namXB = txtNXB.getText();
        String tongSoLuong = txtTongSL.getText();
        String soLuongHienCo = txtSLHC.getText();
        String nhaXuatBan = txtNhaXB.getText();
        String tacGia = txtTacGia.getText();
        String loaiSach = txtLoaiSach.getText();

        // Kiểm tra tính hợp lệ của dữ liệu
        if (maSach.isEmpty() || tenSach.isEmpty() || triGia.isEmpty() || namXB.isEmpty() || tongSoLuong.isEmpty() || soLuongHienCo.isEmpty() || nhaXuatBan.isEmpty() || tacGia.isEmpty() || loaiSach.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ thông tin.");
            return;
        }

        String query = "INSERT INTO SACH (MaSach, TenSach, TriGia, NamXB, TongSoLuong, SoLuongHienCo, MaNXB, MaTG, MaLoai) VALUES (?, ?, ?, ?, ?, ?, (SELECT MaNXB FROM NHAXB WHERE TenNXB = ?), (SELECT MaTG FROM TACGIA WHERE TenTG = ?), (SELECT MaLoai FROM LOAISACH WHERE TenLoai = ?))";

        try (Connection connection = MyConnection.getConnection();
            PreparedStatement preparedStatement = connection.prepareStatement(query)) {

            preparedStatement.setString(1, maSach);
            preparedStatement.setString(2, tenSach);
            preparedStatement.setDouble(3, Double.parseDouble(triGia));
            preparedStatement.setString(4, namXB);
            preparedStatement.setInt(5, Integer.parseInt(tongSoLuong));
            preparedStatement.setInt(6, Integer.parseInt(soLuongHienCo));
            preparedStatement.setString(7, nhaXuatBan);
            preparedStatement.setString(8, tacGia);
            preparedStatement.setString(9, loaiSach);

            int rowsInserted = preparedStatement.executeUpdate();

            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Lưu sách thành công.");

                // Thêm dữ liệu vào bảng tblSach
                DefaultTableModel model = (DefaultTableModel) tblSach.getModel();
                model.addRow(new Object[]{maSach, tenSach, tacGia, soLuongHienCo});
            }
        } catch (SQLException e) {
            // Nếu có lỗi xảy ra trong quá trình kết nối hoặc truy vấn cơ sở dữ liệu.
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi cơ sở dữ liệu: " + e.getMessage());
        }
    }//GEN-LAST:event_btnLuuActionPerformed

    private void btnTimActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimActionPerformed
        // TODO add your handling code here:
        String maSach = txtMaSach.getText();
        String tenSach = txtTenSach.getText();

        // Kiểm tra tính hợp lệ của dữ liệu.
        if (maSach.isEmpty() && tenSach.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập mã sách hoặc tên sách để tìm.");
            return;
        }

        String query = "SELECT SACH.MaSach, SACH.TenSach, SACH.TriGia, SACH.NamXB, SACH.TongSoLuong, SACH.SoLuongHienCo, NHAXB.TenNXB, TACGIA.TenTG, LOAISACH.TenLoai " +
        "FROM SACH " +
        "JOIN NHAXB ON SACH.MaNXB = NHAXB.MaNXB " +
        "JOIN TACGIA ON SACH.MaTG = TACGIA.MaTG " +
        "JOIN LOAISACH ON SACH.MaLoai = LOAISACH.MaLoai " +
        "WHERE SACH.MaSach = ? OR SACH.TenSach = ?";

        try (Connection connection = MyConnection.getConnection();
            PreparedStatement preparedStatement = connection.prepareStatement(query)) {

            if (!maSach.isEmpty()) {
                preparedStatement.setString(1, maSach);
                preparedStatement.setString(2, "");
            } else {
                preparedStatement.setString(1, "");
                preparedStatement.setString(2, tenSach);
            }

            ResultSet resultSet = preparedStatement.executeQuery();

            if (resultSet.next()) {
                txtMaSach.setText(resultSet.getString("MaSach"));
                txtTenSach.setText(resultSet.getString("TenSach"));
                txtTriGia.setText(String.valueOf(resultSet.getDouble("TriGia")));
                txtNXB.setText(resultSet.getString("NamXB"));
                txtTongSL.setText(String.valueOf(resultSet.getInt("TongSoLuong")));
                txtSLHC.setText(String.valueOf(resultSet.getInt("SoLuongHienCo")));
                txtNhaXB.setText(resultSet.getString("TenNXB"));
                txtTacGia.setText(resultSet.getString("TenTG"));
                txtLoaiSach.setText(resultSet.getString("TenLoai"));
            } else {
                JOptionPane.showMessageDialog(this, "Không tìm thấy sách.");
            }
        } catch (SQLException e) {
            // Nếu có lỗi xảy ra trong quá trình kết nối hoặc truy vấn cơ sở dữ liệu.
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi cơ sở dữ liệu: " + e.getMessage());
        }
    }//GEN-LAST:event_btnTimActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
        String maSach = txtMaSach.getText().trim();
        if (maSach.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn sách để xóa.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn xóa sách này không?", "Xác Nhận Xóa", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            String deleteQuery = "DELETE FROM SACH WHERE MaSach = ?";

            try (Connection connection = MyConnection.getConnection();
                PreparedStatement preparedStatement = connection.prepareStatement(deleteQuery)) {

                preparedStatement.setString(1, maSach);
                int affectedRows = preparedStatement.executeUpdate();

                if (affectedRows > 0) {
                    // Xóa khỏi JTable
                    DefaultTableModel model = (DefaultTableModel) tblSach.getModel();
                    int rowCount = model.getRowCount();
                    for (int i = 0; i < rowCount; i++) {
                        if (model.getValueAt(i, 0).equals(maSach)) {
                            model.removeRow(i);
                            break;
                        }
                    }
                    // Xóa thành công
                    loadDataToTable();
                    JOptionPane.showMessageDialog(this, "Sách đã được xóa.");
                    clearInputFields(); // Xóa các trường nhập liệu
                } else {
                    JOptionPane.showMessageDialog(this, "Không tìm thấy sách để xóa.");
                }
            } catch (SQLException e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Lỗi cơ sở dữ liệu: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnXoaActionPerformed

