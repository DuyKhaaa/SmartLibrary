    private void btnXoaNVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaNVActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblDSNhanVien.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn nhân viên cần xóa.");
            return;
        }

        String MaNV = tableModel.getValueAt(selectedRow, 0).toString();

        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn xóa nhân viên này không?", "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            String sql = "delete from NHANVIEN where MaNV = ?";
            try (Connection con = MyConnection.getConnection();
                 PreparedStatement ps = con.prepareStatement(sql)) {
                ps.setString(1, MaNV);
                int rowsAffected = ps.executeUpdate();
                if (rowsAffected > 0) {
                    JOptionPane.showMessageDialog(this, "Xóa nhân viên thành công.");
                    tableModel.removeRow(selectedRow);
                } else {
                    JOptionPane.showMessageDialog(this, "Xóa nhân viên thất bại.");
                }
            } catch (SQLException e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Xóa nhân viên thất bại: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnXoaNVActionPerformed

    private void btnSuaNVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaNVActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblDSNhanVien.getSelectedRow();
        if (selectedRow != -1) { 
            // Lấy thông tin từ bảng
            Object objMaNV = tblDSNhanVien.getValueAt(selectedRow, 0);
            Object objHoTen = tblDSNhanVien.getValueAt(selectedRow, 1);
            Object objNgaySinh = tblDSNhanVien.getValueAt(selectedRow, 2);
            Object objDiaChi = tblDSNhanVien.getValueAt(selectedRow, 3);
            Object objSDT = tblDSNhanVien.getValueAt(selectedRow, 4);
            Object objEmail = tblDSNhanVien.getValueAt(selectedRow, 5);
            Object objNgayVaoLam = tblDSNhanVien.getValueAt(selectedRow, 6);
            Object objMaBP = tblDSNhanVien.getValueAt(selectedRow, 7);
            Object objMatKhau = tblDSNhanVien.getValueAt(selectedRow, 8);
            //kiem tra xem du lieu co null hay khong
            String MaNV = objMaNV != null ? objMaNV.toString() : "";
            String HoTen = objHoTen != null ? objHoTen.toString() : "";
            String NgaySinh = objNgaySinh != null ? objNgaySinh.toString() : "";
            String DiaChi = objDiaChi != null ? objDiaChi.toString() : "";
            String SDT = objSDT != null ? objSDT.toString() : "";
            String Email = objEmail != null ? objEmail.toString() : "";
            String NgayVaoLam = objNgayVaoLam != null ? objNgayVaoLam.toString() : "";
            String MaBP = objMaBP != null ? objMaBP.toString() : "";
            String MatKhau = objMatKhau != null ? objMatKhau.toString() : "";            
            
            ThemNV themnv = new ThemNV();
            themnv.setMaNV(MaNV);
            themnv.setHoTen(HoTen);
            themnv.setNgaySinh(NgaySinh);
            themnv.setDiaChi(DiaChi);
            themnv.setSDT(SDT);
            themnv.setEmail(Email);
            themnv.setNgayVaoLam(NgayVaoLam);
            themnv.setMaBP(MaBP);
            themnv.setMatKhau(MatKhau);
            themnv.setUpdateMode(true); 
            themnv.setVisible(true);
            dispose();               
        } else {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn nhân viên cần sửa thông tin.");
        }
    }//GEN-LAST:event_btnSuaNVActionPerformed

