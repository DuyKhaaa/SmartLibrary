    private void loadData() {
        DefaultTableModel model = (DefaultTableModel) tblMuonTra.getModel();
        model.setRowCount(0); // Xóa dữ liệu cũ

        String query = "SELECT p.MaPhieu, p.TinhTrang, p.NgayMuon, p.NgayTra, p.HanTra, "
                     + "d.HoTen AS HoTenDocGia, n.HoTen AS HoTenNhanVien "
                     + "FROM PHIEUMUONTRA p "
                     + "JOIN DocGia d ON p.MaDG = d.MaDG "
                     + "JOIN NHANVIEN n ON p.MaNV = n.MaNV";

        try (Connection connection = MyConnection.getConnection();
             PreparedStatement ps = connection.prepareStatement(query);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                String maPhieu = rs.getString("MaPhieu");
                String hoTenDocGia = rs.getString("HoTenDocGia");
                String tinhTrang = rs.getString("TinhTrang");
                String ngayMuon = rs.getString("NgayMuon");
                String ngayTra = rs.getString("NgayTra");
                String hanTra = rs.getString("HanTra");
                String hoTenNhanVien = rs.getString("HoTenNhanVien");

                model.addRow(new Object[]{maPhieu, hoTenDocGia, tinhTrang, ngayMuon, hanTra, ngayTra, hoTenNhanVien});
            }
        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Lỗi khi tải dữ liệu: " + e.getMessage());
        }
    }
