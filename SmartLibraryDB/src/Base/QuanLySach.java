    public void loadDataToTable() {
        Connection conn = MyConnection.getConnection();
        DefaultTableModel model = (DefaultTableModel) tblSach.getModel();
        model.setRowCount(0); // Clear the existing data

        String sql = "SELECT MaSach, TenSach, SoLuongHienCo, (SELECT TenTG FROM TACGIA WHERE TACGIA.MaTG = SACH.MaTG) AS TenTG FROM SACH";

        try {
            Statement stmt = conn.createStatement();
            ResultSet rs = stmt.executeQuery(sql);

            while (rs.next()) {
                String maSach = rs.getString("MaSach");
                String tenSach = rs.getString("TenSach");
                int soLuongHienCo = rs.getInt("SoLuongHienCo");
                String tenTG = rs.getString("TenTG");

                model.addRow(new Object[]{maSach, tenSach, tenTG, soLuongHienCo});
            }
            rs.close();
            stmt.close();
            conn.close();
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
