    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblKiemKe.getSelectedRow(); // Lấy dòng được chọn
        if (selectedRow != -1) { // Kiểm tra xem có dòng nào được chọn không
            String maPhieuKK = tblKiemKe.getValueAt(selectedRow, 0).toString(); // Lấy mã phiếu kiểm kê

            // Hiển thị hộp thoại xác nhận
            int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn xóa không?", "Xác nhận xóa", javax.swing.JOptionPane.YES_NO_OPTION);

            if (confirm == javax.swing.JOptionPane.YES_OPTION) {
                try {
                    // Kết nối cơ sở dữ liệu
                    Connection conn = MyConnection.getConnection();

                    // Xóa dữ liệu trong CTPhieuKK
                    String sqlCT = "DELETE FROM CTPhieuKK WHERE MaPhieuKK = ?";
                    PreparedStatement pstmtCT = conn.prepareStatement(sqlCT);
                    pstmtCT.setString(1, maPhieuKK);
                    pstmtCT.executeUpdate();

                    // Xóa dữ liệu trong PhieuKiemKe
                    String sqlPhieu = "DELETE FROM PhieuKiemKe WHERE MaPhieuKK = ?";
                    PreparedStatement pstmtPhieu = conn.prepareStatement(sqlPhieu);
                    pstmtPhieu.setString(1, maPhieuKK);
                    pstmtPhieu.executeUpdate();

                    // Đóng kết nối
                    pstmtCT.close();
                    pstmtPhieu.close();
                    conn.close();

                    // Cập nhật lại bảng
                    loadData(); // Gọi lại phương thức loadData để cập nhật bảng
                    javax.swing.JOptionPane.showMessageDialog(this, "Xóa thành công!");
                } catch (Exception e) {
                    e.printStackTrace();
                    javax.swing.JOptionPane.showMessageDialog(this, "Xóa không thành công: " + e.getMessage());
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Vui lòng chọn một dòng để xóa.");
        }
    }//GEN-LAST:event_btnXoaActionPerformed

    private void btnChinhSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChinhSuaActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblKiemKe.getSelectedRow(); // Lấy dòng được chọn
        if (selectedRow != -1) {
            String maPhieuKK = tblKiemKe.getValueAt(selectedRow, 0).toString(); // Lấy Mã Phiếu Kiểm Kê
            String ngayLap = tblKiemKe.getValueAt(selectedRow, 1).toString(); // Lấy Ngày Lập

            // Mở form LapPhieuKiemKe và thiết lập giá trị
            LapPhieuKiemKe lapPhieuKiemKe = new LapPhieuKiemKe();
            lapPhieuKiemKe.setTxtMaKK(maPhieuKK);
            lapPhieuKiemKe.setTxtNgayLap(ngayLap);

            // Tải chi tiết từ CTPHIEUKK vào bảng
            DefaultTableModel model = new DefaultTableModel(new Object[]{"Mã sách", "Tên sách", "Số lượng", "Tình trạng"}, 0);
            String detailQuery = "SELECT MaSach, SoLuongKK, TinhTrang FROM CTPHIEUKK WHERE MaPhieuKK = ?";

            try (Connection connection = MyConnection.getConnection();
                 PreparedStatement psDetail = connection.prepareStatement(detailQuery)) {
                psDetail.setString(1, maPhieuKK);
                ResultSet rsDetail = psDetail.executeQuery();

                while (rsDetail.next()) {
                    String maSach = rsDetail.getString("MaSach");
                    int soLuong = rsDetail.getInt("SoLuongKK");
                    String tinhTrang = rsDetail.getString("TinhTrang");

                    // Truy vấn để lấy tên sách từ bảng SACH
                    String tenSach = "";
                    String bookQuery = "SELECT TenSach FROM SACH WHERE MaSach = ?";
                    try (PreparedStatement psBook = connection.prepareStatement(bookQuery)) {
                        psBook.setString(1, maSach);
                        ResultSet rsBook = psBook.executeQuery();
                        if (rsBook.next()) {
                            tenSach = rsBook.getString("TenSach");
                        }
                    } catch (SQLException e) {
                        e.printStackTrace();
                        JOptionPane.showMessageDialog(this, "Lỗi khi lấy tên sách: " + e.getMessage());
                    }

                    model.addRow(new Object[]{maSach, tenSach, soLuong, tinhTrang}); // Thêm tên sách vào mô hình
                }
            } catch (SQLException e) {
                e.printStackTrace();
                JOptionPane.showMessageDialog(this, "Lỗi khi lấy chi tiết phiếu kiểm kê: " + e.getMessage());
            }

            lapPhieuKiemKe.setTblCTKK(model); // Gọi phương thức để thiết lập bảng
            lapPhieuKiemKe.setVisible(true); // Hiển thị form
            // Đóng trang hiện tại
            this.dispose(); // Đóng form QLKiemKe
        } else {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn một dòng để chỉnh sửa.");
        }
    }//GEN-LAST:event_btnChinhSuaActionPerformed

